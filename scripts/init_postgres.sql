-- =============================================================================
-- init_postgres.sql — NexusCore Database Schema Initialization
-- =============================================================================
-- PURPOSE:
--   This SQL script runs automatically when the PostgreSQL container starts
--   for the first time (mounted at /docker-entrypoint-initdb.d/).
--
-- TABLES:
--   1. api_keys        — Stores and manages API key credentials with rate limit config
--   2. llm_audit_logs  — Immutable append-only audit log of every LLM request
--
-- DESIGN PRINCIPLES:
--   - UUIDs as primary keys: Globally unique, prevents enumeration attacks.
--   - Timestamps with timezone: All times stored in UTC (timestamptz) to avoid
--     DST ambiguity when users span multiple timezones.
--   - Immutable audit logs: No UPDATE/DELETE on llm_audit_logs — only INSERT.
--     This is the append-only log pattern for compliance and forensic analysis.
-- =============================================================================

-- Enable the UUID extension (built into Postgres contrib)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- =============================================================================
-- TABLE 1: api_keys
-- =============================================================================
-- PURPOSE: Store API keys that clients use to authenticate with the Gateway.
--   The Gateway's RateLimitFilter validates the Authorization header against
--   this table and applies per-key rate limits.
--
-- KEY DESIGN DECISIONS:
--   - `key_hash` stores a SHA-256 hash of the actual API key (never plaintext).
--     The gateway hashes the incoming key and compares the hash. This means
--     a database breach does not expose raw credentials.
--   - `rate_limit_rpm` is per-key: enterprise customers get higher limits.
--   - `is_active` allows instant key revocation without deleting audit history.
-- =============================================================================
CREATE TABLE IF NOT EXISTS api_keys (
    -- Surrogate primary key: UUID v4 generated by Postgres
    id              UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

    -- Human-readable label for the key (e.g., "Production Mobile App Key")
    name            VARCHAR(255) NOT NULL,

    -- SHA-256 hash of the actual API key. NEVER store the raw key.
    -- The Gateway computes: SHA256("Bearer sk-...") and looks up this column.
    key_hash        VARCHAR(64) UNIQUE NOT NULL,

    -- Rate limit: requests per minute for this key.
    -- Default: 60 RPM (1 request/second average, burst up to 60 in a minute).
    -- The Redis token bucket is seeded from this value.
    rate_limit_rpm  INTEGER NOT NULL DEFAULT 60,

    -- Soft delete: set to false to immediately block a compromised key.
    -- All historical audit logs retain their foreign key reference.
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,

    -- Tenant ID for multi-tenant deployments (maps to organization/customer)
    tenant_id       UUID,

    -- Timestamps (all in UTC via TIMESTAMPTZ)
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_used_at    TIMESTAMPTZ,
    expires_at      TIMESTAMPTZ  -- NULL means never expires
);

-- Index for the hot path: Gateway validates keys on every request.
-- key_hash lookup must be O(log n) or better. B-tree index handles this.
CREATE INDEX IF NOT EXISTS idx_api_keys_hash ON api_keys(key_hash);
-- Index for tenant-scoped queries (e.g., "show all keys for tenant X")
CREATE INDEX IF NOT EXISTS idx_api_keys_tenant ON api_keys(tenant_id);

-- =============================================================================
-- TABLE 2: llm_audit_logs
-- =============================================================================
-- PURPOSE: Immutable record of every LLM request processed by NexusCore.
--   Written by KafkaConsumerService (MVP 4) whenever the Python worker
--   emits a completion event to the `ai.telemetry.events` topic.
--
-- WHY IMMUTABLE?
--   For compliance (SOC 2, HIPAA, GDPR Article 30), you must be able to prove
--   what data was sent to which AI provider at what time. An immutable log
--   (INSERT only, no UPDATE/DELETE) ensures audit integrity.
--
-- COST TRACKING:
--   token_count_input / token_count_output enable precise per-request cost
--   calculation. Cost = (input_tokens / 1M) * input_price + (output_tokens / 1M) * output_price.
--   This powers the "cost savings from cache hits" dashboard metric.
-- =============================================================================
CREATE TABLE IF NOT EXISTS llm_audit_logs (
    -- Surrogate primary key
    id                  UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

    -- The request ID propagated from Gateway → Kafka → Python worker → here.
    -- Enables end-to-end trace correlation with OpenTelemetry (MVP 6).
    request_id          VARCHAR(36) NOT NULL,

    -- The API key that initiated this request (stored as hash, not raw key)
    api_key_hash        VARCHAR(64),

    -- The prompt text sent to the LLM (may be truncated for storage efficiency)
    prompt_text         TEXT,

    -- Which AI model actually processed this request
    model_used          VARCHAR(100) NOT NULL,

    -- Whether the response came from the semantic cache or went to the LLM
    -- Values: 'SEMANTIC_HIT', 'MISS', 'FALLBACK_HIT'
    cache_status        VARCHAR(20) NOT NULL,

    -- Token usage — critical for cost accounting
    token_count_input   INTEGER,
    token_count_output  INTEGER,

    -- Wall-clock latency from gateway receipt to response delivery (milliseconds)
    latency_ms          INTEGER,

    -- The cosine similarity score if a cache lookup was performed
    -- Range: 0.0 to 1.0. NULL if no vector search was attempted.
    cosine_similarity   DECIMAL(6, 5),

    -- OpenTelemetry distributed trace ID for cross-service debugging
    trace_id            VARCHAR(32),

    -- HTTP status code returned to the client (200, 429, 500, etc.)
    http_status_code    INTEGER,

    -- Immutable timestamp: set on insert, never modified
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes for common query patterns in the analytics/cost dashboard:
-- 1. Find all logs for a specific request (O2O mapping: request → log)
CREATE INDEX IF NOT EXISTS idx_audit_request_id ON llm_audit_logs(request_id);
-- 2. Time-range queries: "show all requests in the last hour"
CREATE INDEX IF NOT EXISTS idx_audit_created_at ON llm_audit_logs(created_at DESC);
-- 3. Filter by model to compare cost across providers
CREATE INDEX IF NOT EXISTS idx_audit_model ON llm_audit_logs(model_used);
-- 4. Filter cache hits to calculate savings vs. LLM spend
CREATE INDEX IF NOT EXISTS idx_audit_cache_status ON llm_audit_logs(cache_status);

